"""Sample queries script (design section 1.2 item 18 / implementation-plan.md's Phase 13
task 2): runs the query layer's six worked example questions against the real `app.db`
(populated by `eval.run_eval` or by using the app normally) and writes each question, the SQL
Gemini wrote for it, and the result to `docs/sample-queries.md`.

This is a real spend of Gemini free-tier quota (one call per question, six total). It is
never run automatically -- only when explicitly invoked, same as `eval.run_eval`.

Run from the repo root, after at least one document has gone through the pipeline (so
`data/app.db` has something to query against):

    backend\\.venv\\Scripts\\python.exe -m eval.run_sample_queries
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND_DIR = REPO_ROOT / "backend"
sys.path.insert(0, str(BACKEND_DIR))
sys.path.insert(0, str(REPO_ROOT))

from app.config import settings  # noqa: E402
from app.llm.budget import CallBudget  # noqa: E402
from app.llm.client import LLMClient  # noqa: E402
from app.llm.gemini_transport import GeminiTransport  # noqa: E402
from app.llm.recorder import CallRecorder  # noqa: E402
from app.query.service import answer_question  # noqa: E402
from app.store.db import db_path  # noqa: E402

OUT_PATH = REPO_ROOT / "docs" / "sample-queries.md"

# The same six questions the query_v1 prompt's worked examples cover (see
# backend/app/llm/prompts/query_v1.txt) -- proof the real answers match what the prompt
# promises, not just the worked examples themselves.
QUESTIONS = [
    "How many documents were flagged for review this week?",
    "Which documents need an amendment, and why?",
    "What is the most common mismatched field?",
    "Show everything with an uncertain HS code.",
    "What was the average cost per document?",
    "Which runs were overridden by code?",
]


def _make_client(run_id: str) -> LLMClient:
    return LLMClient(
        transport=GeminiTransport(api_key=settings.gemini_api_key),
        primary_model=settings.gemini_model,
        fallback_model=settings.gemini_fallback_model,
        budget=CallBudget(max_calls=6),
        recorder=CallRecorder(),
        run_id=run_id,
    )


def _format_value(value: object) -> str:
    if value is None:
        return "_(null)_"
    return str(value)


def _format_table(columns: tuple[str, ...], rows: tuple[tuple, ...]) -> str:
    if not rows:
        return "_(no rows)_"
    header = "| " + " | ".join(columns) + " |"
    sep = "|" + "|".join("---" for _ in columns) + "|"
    body = "\n".join(
        "| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows
    )
    return "\n".join([header, sep, body])


def main() -> int:
    path = db_path()
    if not path.exists():
        print(
            f"No database at {path}. Run at least one document through the pipeline first "
            "(e.g. `backend\\.venv\\Scripts\\python.exe -m eval.run_eval`, or `app.cli run`).",
            file=sys.stderr,
        )
        return 1

    lines = [
        "# Sample queries",
        "",
        "Six plain-English questions run against the real, populated `data/app.db`, through "
        "the same `answer_question()` the Ask box calls. Each question spends one real "
        "Gemini call. Generated by `python -m eval.run_sample_queries`.",
        "",
    ]

    today = date.today()
    for i, question in enumerate(QUESTIONS, start=1):
        client = _make_client(run_id=f"sample-query-{i}")
        answer = answer_question(question=question, db_path=path, client=client, today=today)

        lines.append(f"## {i}. {question}")
        lines.append("")
        lines.append(f"**SQL:**\n```sql\n{answer.sql}\n```")
        lines.append("")
        lines.append(f"**Explanation:** {answer.explanation}")
        lines.append("")
        if answer.kind == "refused":
            lines.append(f"**Result:** refused -- {answer.error}")
        elif answer.kind == "single_value":
            lines.append(f"**Result:** {_format_value(answer.value)}")
        else:
            lines.append(f"**Result:**\n\n{_format_table(answer.columns, answer.rows)}")
        lines.append("")
        print(f"[{i}/{len(QUESTIONS)}] {question} -> {answer.kind}")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
